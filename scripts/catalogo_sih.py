def get_catalogo_completo_df(lang: str = "pt") -> pd.DataFrame:
    rows = []
    s_map = STATUS_MAP.get(lang, STATUS_MAP["pt"])
    for col, b_pt, b_en, d_pt, d_en, s_key in CATALOGO_SIH_COMPLETO:
        if lang == "en":
            rows.append({
                "Column": col,
                "Domain": b_en,
                "Usage Status": s_map[s_key],
                "Description": d_en,
                "_status_key": s_key,
            })
        elif lang == "es":
            rows.append({
                "Columna": col,
                "Bloque": DOMAINS_ES.get(b_pt, b_pt),
                "Uso en el Proyecto": s_map[s_key],
                "Significado y Motivo": DESCS_ES.get(col, d_pt),
                "_status_key": s_key,
            })
        else:
            rows.append({
                "Coluna": col,
                "Bloco": b_pt,
                "Uso no Projeto": s_map[s_key],
                "Significado e Motivo": d_pt,
                "_status_key": s_key,
            })
    return pd.DataFrame(rows)
